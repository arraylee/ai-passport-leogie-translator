#!/usr/bin/env python3
"""Deterministic extraction of the authorized Leogie sprite sheet; no redrawing."""
import hashlib
import json
from pathlib import Path
import subprocess
import re
import zlib
import numpy as np
from PIL import Image
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / 'assets/leogie'
BOARD = ROOT / 'main/boards/ai-passport-leogie'


def main():
    source = Image.open(ASSETS / 'source.png').convert('RGBA')
    assert source.size == (1536, 2288)
    positions = [(0, 0), (1, 0), (3, 0), (1, 6), (0, 7), (2, 7),
                 (0, 4), (1, 4), (1, 3), (2, 3)]
    code = ['/* Generated by scripts/leogie_assets.py from user-owned Leogie art. */', '#include "leogie_art.h"']
    frames = []
    for index, (col, row) in enumerate(positions):
        frame = source.crop((col*192, row*208, (col+1)*192, (row+1)*208))
        frame = frame.resize((72, 78), Image.Resampling.LANCZOS)
        background = Image.new('RGBA', frame.size, (246, 243, 235, 255))
        background.alpha_composite(frame)
        background.convert('RGB').save(ASSETS / f'frame-{index:02}.png')
        rgb = np.asarray(background.convert('RGB'), dtype=np.uint16)
        pixels = ((rgb[:,:,0] >> 3) << 11) | ((rgb[:,:,1] >> 2) << 5) | (rgb[:,:,2] >> 3)
        raw = pixels.astype('<u2').tobytes()
        path = ASSETS / f'frame-{index:02}.rgb565'
        path.write_bytes(raw)
        frames.append({'path': str(path.relative_to(ROOT)), 'source_cell': [col, row],
                       'sha256': hashlib.sha256(raw).hexdigest()})
        code += [f'static const uint8_t pixels_{index}[] = {{']
        code += [','.join(f'0x{b:02x}' for b in raw[x:x+32])+',' for x in range(0,len(raw),32)]
        code += ['};']
    code += [f'const lv_image_dsc_t leogie_frames[{len(frames)}] = {{']
    for i in range(len(frames)):
        code += [f'{{.header = {{.magic=LV_IMAGE_HEADER_MAGIC, .cf=LV_COLOR_FORMAT_RGB565, .w=72, .h=78, .stride=144}}, .data_size=sizeof(pixels_{i}), .data=pixels_{i}}},']
    code += ['};']
    (BOARD/'leogie_art.c').write_text('\n'.join(code)+'\n')
    (BOARD/'leogie_art.h').write_text('#pragma once\n#include <lvgl.h>\n#ifdef __cplusplus\nextern "C" {\n#endif\nextern const lv_image_dsc_t leogie_frames[10];\n#ifdef __cplusplus\n}\n#endif\n')
    (ASSETS/'manifest.json').write_text(json.dumps({'frame_size':[72,78],
        'source_sha256':hashlib.sha256((ASSETS/'source.png').read_bytes()).hexdigest(),
        'frames':frames},indent=2)+'\n')
    from leogie_font import main as build_font
    build_font()
    print(f'Generated {len(frames)} historical RGB565 frames')


if __name__ == '__main__': main()
