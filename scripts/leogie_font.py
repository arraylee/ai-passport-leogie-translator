#!/usr/bin/env python3
"""Build the self-contained native-size community font; never touches artwork."""
import hashlib
import json
from pathlib import Path
import re
import subprocess
import zlib

from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / 'assets/leogie'
BOARD = ROOT / 'main/boards/ai-passport-leogie'


def codepoints():
    points = set(range(32, 256))
    for lo, hi in [(0x2000, 0x2070), (0x3000, 0x3040), (0xff01, 0xff60), (0xffe0, 0xffe7)]:
        points.update(range(lo, hi))
    han = set()
    for a in range(0xb0, 0xf8):
        for b in range(0xa1, 0xff):
            try:
                han.add(ord(bytes([a, b]).decode('gb2312')))
            except UnicodeDecodeError:
                pass
    assert len(han) == 6763
    points.update(han)
    # Include actual localized strings, not just a Han-range heuristic.
    locale = json.loads((ROOT / 'main/assets/locales/zh-CN/language.json').read_text())
    def visit(value):
        if isinstance(value, str):
            points.update(ord(c) for c in value if ord(c) >= 32)
        elif isinstance(value, dict):
            for item in value.values(): visit(item)
        elif isinstance(value, list):
            for item in value: visit(item)
    visit(locale)
    for source in BOARD.glob('*.cc'):
        for literal in re.findall(r'"([^"\n]*)"', source.read_text()):
            points.update(ord(c) for c in literal if ord(c) >= 32)
    available = TTFont(ASSETS / 'LXGWWenKai-Medium.ttf').getBestCmap()
    assert han <= available.keys(), 'Source font lacks required GB2312 glyphs'
    return sorted(points & available.keys())


def main():
    cps = codepoints()
    out = BOARD / 'leogie_font20.c'
    subprocess.run(['npx', '--yes', 'lv_font_conv@1.5.3', '--font',
        str(ASSETS / 'LXGWWenKai-Medium.ttf'), '--size', '20', '--bpp', '4',
        '--no-kerning', '--format', 'lvgl', '--lv-include', 'lvgl.h',
        '--symbols', ''.join(map(chr, cps)), '--output', str(out)], check=True)
    generated = out.read_text()
    match = re.search(r'static LV_ATTRIBUTE_LARGE_CONST const uint8_t glyph_bitmap\[\] = \{(.*?)\n\};', generated, re.S)
    if not match: raise RuntimeError('Unexpected font converter output')
    bitmap = bytes(int(x, 16) for x in re.findall(r'0x[0-9a-fA-F]+', match[1]))
    # Match 0.2.0 layout exactly, including its baseline, without runtime scaling.
    generated = re.sub(r'\.line_height = \d+,', '.line_height = 29,', generated)
    generated = re.sub(r'\.base_line = \d+,', '.base_line = 7,', generated)
    generated = re.sub(r' \* Opts: .*\n', ' * Generated by scripts/leogie_font.py (lv_font_conv 1.5.3).\n', generated)
    notice = 'LEOGIE_FONT_LICENSE_BEGIN\n' + (ASSETS / 'FONT-NOTICES.txt').read_text() + '\nLEOGIE_FONT_LICENSE_END\n'
    declaration = 'static const char leogie_font_license[] = ' + json.dumps(notice) + ';\n'
    marker = '/*Initialize a public general font descriptor*/'
    generated = generated.replace(marker, declaration + '\n' + marker)
    generated = generated.replace('.user_data = NULL,', '.user_data = (void*)leogie_font_license,')
    out.write_text(generated)
    (ASSETS / 'font-bitmap.bin').write_bytes(bitmap)
    (BOARD / 'leogie_font_data.h').write_text('#pragma once\n#define LEOGIE_FONT_EMBEDDED 1\n' +
        f'#define LEOGIE_FONT_BYTES {len(bitmap)}u\n#define LEOGIE_FONT_CRC 0x{zlib.crc32(bitmap):08x}u\n')
    manifest = {'storage': 'embedded-app', 'repertoire': 'GB2312 Han + Latin-1 + UI and punctuation',
        'size': 20, 'bpp': 4, 'bitmap_bytes': len(bitmap),
        'bitmap_sha256': hashlib.sha256(bitmap).hexdigest(), 'bitmap_crc32': zlib.crc32(bitmap),
        'line_height': 29, 'codepoints': cps,
        'source_sha256': hashlib.sha256((ASSETS / 'LXGWWenKai-Medium.ttf').read_bytes()).hexdigest()}
    (ASSETS / 'font-manifest.json').write_text(json.dumps(manifest, indent=2)+'\n')
    print(f'Embedded font: {len(cps)} glyphs, {len(bitmap)} bitmap bytes, 20px/4bpp')


if __name__ == '__main__': main()
