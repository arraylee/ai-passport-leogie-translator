#!/usr/bin/env python3
"""Convert the approved cartoon atlas to native indexed LVGL sprites; no font changes."""
from pathlib import Path
import hashlib
import json
from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / 'assets/leogie/cartoon'
BOARD = ROOT / 'main/boards/ai-passport-leogie'
POSES = ['idle', 'listening', 'thinking', 'speaking']


def main():
    source = Image.open(ASSETS / 'source.png').convert('RGBA')
    width, height = source.size
    frames = []
    code = ['/* Generated by scripts/leogie_cartoon_assets.py. */', '#include "leogie_art.h"']
    for size, w, h in [('large', 180, 160), ('small', 120, 106)]:
        for i, pose in enumerate(POSES):
            x, y = i % 2, i // 2
            cell = source.crop((x*width//2, y*height//2, (x+1)*width//2, (y+1)*height//2))
            alpha = cell.getchannel('A').point(lambda v: v if v >= 24 else 0)
            cell.putalpha(alpha)
            box = alpha.getbbox()
            if box is None:
                raise ValueError(f'Empty pose {pose}')
            sprite = ImageOps.contain(cell.crop(box), (w-4, h-4), Image.Resampling.LANCZOS)
            canvas = Image.new('RGBA', (w, h))
            canvas.alpha_composite(sprite, ((w-sprite.width)//2, h-sprite.height))
            indexed = canvas.quantize(colors=256, method=Image.Quantize.FASTOCTREE, dither=Image.Dither.NONE)
            rgba = indexed.getpalette('RGBA')
            rgba += [0] * (1024-len(rgba))
            palette = bytearray()
            for j in range(0, 1024, 4):
                r,g,b,a = rgba[j:j+4]
                palette.extend((b,g,r,a))
            raw = bytes(palette) + indexed.tobytes()
            name = f'{pose}-{size}'
            (ASSETS / f'{name}.i8').write_bytes(raw)
            indexed.convert('RGBA').save(ASSETS / f'{name}.png')
            frames.append({'pose':pose, 'size':size, 'width':w, 'height':h,
                           'bytes':len(raw), 'sha256':hashlib.sha256(raw).hexdigest()})
            symbol = f'{pose}_{size}'
            code.append(f'static const uint8_t {symbol}[] = {{')
            code.extend(','.join(f'0x{b:02x}' for b in raw[k:k+32])+',' for k in range(0,len(raw),32))
            code.append('};')
        code.append(f'const lv_image_dsc_t leogie_{size}[4] = {{')
        for pose in POSES:
            symbol = f'{pose}_{size}'
            code.append(f'{{.header={{.magic=LV_IMAGE_HEADER_MAGIC,.cf=LV_COLOR_FORMAT_I8,.w={w},.h={h},.stride={w}}},.data_size=sizeof({symbol}),.data={symbol}}},')
        code.append('};')
    (BOARD / 'leogie_art.c').write_text('\n'.join(code)+'\n')
    (BOARD / 'leogie_art.h').write_text('''#pragma once
#include <lvgl.h>
#ifdef __cplusplus
extern "C" {
#endif
extern const lv_image_dsc_t leogie_large[4];
extern const lv_image_dsc_t leogie_small[4];
#ifdef __cplusplus
}
#endif
''')
    (ASSETS / 'manifest.json').write_text(json.dumps({'format':'LVGL I8 BGRA palette',
        'poses':POSES, 'source_sha256':hashlib.sha256((ASSETS/'source.png').read_bytes()).hexdigest(),
        'frames':frames, 'total_bytes':sum(f['bytes'] for f in frames)},indent=2)+'\n')
    print(f'Generated {len(frames)} native sprites, {sum(f["bytes"] for f in frames)} bytes')


if __name__ == '__main__':
    main()
