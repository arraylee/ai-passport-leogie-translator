#!/usr/bin/env python3
"""Generate original brisk alarm audio and native 48px timer digits."""
import json
import math
from pathlib import Path
import re
import struct
import subprocess
import wave

ROOT = Path(__file__).resolve().parents[1]
BOARD = ROOT / 'main/boards/ai-passport-leogie'
ASSETS = ROOT / 'assets/leogie/timer'

def main():
    ASSETS.mkdir(parents=True, exist_ok=True)
    rate = 24000
    notes = [880, 1174.66, 880, 1174.66, 1318.51, 1318.51]
    samples = []
    for i in range(rate * 6 // 10):
        beat = i // (rate // 10)
        t = (i % (rate // 10)) / rate
        env = max(0, min(1, t / .005, (.080 - t) / .008))
        phase = 2 * math.pi * notes[beat] * t
        samples.append(round(26000 * env * (math.sin(phase) + .15 * math.sin(2 * phase)) / 1.15))
    wav = ASSETS / 'alarm.wav'
    with wave.open(str(wav), 'wb') as stream:
        stream.setparams((1, 2, rate, 0, 'NONE', 'not compressed'))
        stream.writeframes(struct.pack('<' + 'h' * len(samples), *samples))
    ogg = ASSETS / 'alarm.ogg'
    subprocess.run(['ffmpeg', '-v', 'error', '-y', '-i', str(wav), '-map_metadata', '-1',
        '-c:a', 'libopus', '-ar', str(rate), '-b:a', '24k', '-vbr', 'off',
        '-frame_duration', '60', '-fflags', '+bitexact', '-flags:a', '+bitexact', str(ogg)], check=True)
    data = ogg.read_bytes()
    header = '#pragma once\n#include <cstddef>\n#include <cstdint>\nextern const uint8_t leogie_alarm[];\nextern const size_t leogie_alarm_size;\n'
    (BOARD / 'leogie_alarm.h').write_text(header)
    rows = [', '.join(f'0x{x:02x}' for x in data[i:i+16]) for i in range(0, len(data), 16)]
    (BOARD / 'leogie_alarm.cc').write_text('// Generated by scripts/leogie_timer_assets.py. Original synthesized six-note alarm.\n#include "leogie_alarm.h"\nconst uint8_t leogie_alarm[] = {\n' + ',\n'.join(rows) + '\n};\nconst size_t leogie_alarm_size = sizeof(leogie_alarm);\n')
    font = BOARD / 'leogie_digits48.c'
    subprocess.run(['npx', '--yes', 'lv_font_conv@1.5.3', '--font', str(ROOT / 'assets/leogie/LXGWWenKai-Medium.ttf'),
        '--size', '48', '--bpp', '4', '--no-kerning', '--format', 'lvgl', '--lv-include', 'lvgl.h',
        '--symbols', '0123456789', '--output', str(font)], check=True)
    text = re.sub(r' \* Opts: .*\n', ' * Generated by scripts/leogie_timer_assets.py; LXGW WenKai, SIL OFL 1.1 (FONT-NOTICES.txt).\n', font.read_text())
    font.write_text(text)
    (ASSETS / 'manifest.json').write_text(json.dumps({'original_synthesis': True, 'duration_ms': 600,
        'sample_rate': rate, 'opus_frame_ms': 60, 'ogg_bytes': len(data), 'digits': '0123456789',
        'font_size': 48, 'font_bpp': 4}, indent=2) + '\n')
    print(f'Alarm: {len(data)} bytes; original 600ms, six 100ms beats. Digits: 48px/4bpp.')

if __name__ == '__main__': main()
